// Command line entry point.
//   npm run generate -- [scenario|all]
//   npm run reconcile -- --scenario 07-realistic [--fax rules|llm|hybrid --model qwen2.5:7b] [--basis decision|receipt]
//   npm run reconcile -- --input path/to/your/exports --out path/to/output --year 2026
//   npm run demo                              (generate + reconcile every scenario, write output/SUMMARY.md)
//   npm run explain -- --scenario 07-realistic --case C00012 | --metric standard.approvedPct | --record fax:FX-000031

import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { SCENARIOS, getScenario } from './synth/scenarios.js';
import { generate } from './synth/generate.js';
import { run, writeOutputs, type RunResult } from './pipeline.js';
import { ollamaExtractor } from './ingest/faxLlm.js';
import { formatWall } from './util/time.js';

const ROOT = resolve(import.meta.dirname, '..');
const DATA = join(ROOT, 'data', 'scenarios');
const OUT = join(ROOT, 'output');

function args(argv: string[]) {
  const pos: string[] = [];
  const flags: Record<string, string> = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith('--')) {
      const k = argv[i].slice(2);
      const v = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : 'true';
      flags[k] = v;
    } else pos.push(argv[i]);
  }
  return { pos, flags };
}

function runOpts(flags: Record<string, string>, year: number) {
  const faxMode = (flags.fax ?? 'rules') as 'rules' | 'llm' | 'hybrid';
  return {
    year,
    basis: (flags.basis ?? 'decision') as 'decision' | 'receipt',
    faxMode,
    llm: faxMode === 'rules' ? undefined : ollamaExtractor({ model: flags.model ?? 'qwen2.5:7b', host: flags.ollama }),
    match: flags.window ? { windowDays: Number(flags.window) } : undefined,
  };
}

function printSummary(r: RunResult) {
  const get = (rep: RunResult['naive'] | undefined, k: string) => rep?.metrics.find((m) => m.key === k)?.value;
  const show = (v: number | null | undefined) => (v === null || v === undefined ? '-' : String(v));
  console.log(`\n${r.title}  [${r.name}]`);
  console.log(`  records ${r.counts.records} | submissions ${r.counts.submissions} | status calls ignored ${r.counts.inquiries} | appeals ${r.counts.appeals}`);
  console.log(`  reconciled requests ${r.counts.cases} | review queue ${r.counts.reviewItems}${r.counts.faxLlmCalls ? ` | LLM fax reads ${r.counts.faxLlmCalls}` : ''}`);
  const rows = ['standard.total', 'standard.approvedPct', 'standard.medianHours', 'expedited.total', 'expedited.approvedPct', 'expedited.medianHours', 'standard.approvedAfterAppealPct', 'all.extendedApprovedPct'];
  console.log(`  ${'metric'.padEnd(34)}${'naive'.padStart(10)}${'reconciled'.padStart(12)}${r.truth ? 'answer key'.padStart(12) : ''}`);
  for (const k of rows) {
    console.log(`  ${k.padEnd(34)}${show(get(r.naive, k)).padStart(10)}${show(get(r.reconciled, k)).padStart(12)}${r.truth ? show(get(r.truth, k)).padStart(12) : ''}`);
  }
  if (r.evaluation) {
    const e = r.evaluation;
    console.log(`  matching: precision ${e.pairPrecision} recall ${e.pairRecall} exact ${e.exactRequestAccuracy} (wrong merges ${e.falseMerges}, missed ${e.missedMerges}); appeals linked ${e.appealLinkAccuracy}`);
  }
  if (r.warnings.length) console.log(`  warnings: ${r.warnings.length} (see metrics.json)`);
}

async function runScenario(name: string, flags: Record<string, string>) {
  const cfg = getScenario(name);
  const dir = join(DATA, cfg.name);
  if (!existsSync(join(dir, 'portal_export.csv'))) generate(cfg, dir);
  const r = await run(cfg.name, dir, { ...runOpts(flags, cfg.year), title: cfg.title, description: cfg.whatItTests });
  writeOutputs(r, join(OUT, cfg.name));
  printSummary(r);
  return r;
}

function summaryMarkdown(results: RunResult[]): string {
  const m = (r: RunResult, rep: 'naive' | 'reconciled' | 'truth', k: string) => r[rep]?.metrics.find((x) => x.key === k)?.value ?? '-';
  const lines = [
    '# Results across all scenarios',
    '',
    'Generated by `npm run demo`. Naive = sum of per-channel reports. Reconciled = this tool. Key = answer key.',
    '',
    '| Scenario | Requests naive / reconciled / key | Std approved % naive / rec / key | Std median h naive / rec / key | Merge precision | Merge recall | Review items |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const r of results) {
    const tot = (rep: 'naive' | 'reconciled' | 'truth') => {
      const s = m(r, rep, 'standard.total');
      const e = m(r, rep, 'expedited.total');
      return typeof s === 'number' && typeof e === 'number' ? s + e : '-';
    };
    lines.push(
      `| ${r.title} | ${tot('naive')} / ${tot('reconciled')} / ${tot('truth')} | ${m(r, 'naive', 'standard.approvedPct')} / ${m(r, 'reconciled', 'standard.approvedPct')} / ${m(r, 'truth', 'standard.approvedPct')} | ${m(r, 'naive', 'standard.medianHours')} / ${m(r, 'reconciled', 'standard.medianHours')} / ${m(r, 'truth', 'standard.medianHours')} | ${r.evaluation?.pairPrecision ?? '-'} | ${r.evaluation?.pairRecall ?? '-'} | ${r.counts.reviewItems} |`,
    );
  }
  return lines.join('\n') + '\n';
}

async function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  const { pos, flags } = args(rest);
  switch (cmd) {
    case 'generate': {
      const which = pos[0] ?? flags.scenario ?? 'all';
      for (const s of which === 'all' ? SCENARIOS : [getScenario(which)]) {
        const t = generate(s, join(DATA, s.name));
        console.log(`generated ${s.name}: ${t.requests.length} true requests -> data/scenarios/${s.name}/`);
      }
      break;
    }
    case 'reconcile': {
      if (flags.input) {
        const input = resolve(flags.input);
        const out = resolve(flags.out ?? join(input, 'reconciler-output'));
        const r = await run(flags.name ?? 'custom', input, { ...runOpts(flags, Number(flags.year ?? new Date().getFullYear() - 1)), title: flags.name ?? 'Your data' });
        writeOutputs(r, out);
        printSummary(r);
        console.log(`\noutputs written to ${out}`);
      } else {
        const which = flags.scenario ?? pos[0] ?? '07-realistic';
        for (const s of which === 'all' ? SCENARIOS : [getScenario(which)]) await runScenario(s.name, flags);
        console.log(`\nopen output/<scenario>/report.html in a browser`);
      }
      break;
    }
    case 'all': {
      const results: RunResult[] = [];
      for (const s of SCENARIOS) {
        generate(s, join(DATA, s.name));
        results.push(await runScenario(s.name, flags));
      }
      mkdirSync(OUT, { recursive: true });
      writeFileSync(join(OUT, 'SUMMARY.md'), summaryMarkdown(results));
      console.log(`\nwrote output/SUMMARY.md; open output/07-realistic/report.html for the demo`);
      break;
    }
    case 'explain': {
      const s = getScenario(flags.scenario ?? '07-realistic');
      const r = await run(s.name, join(DATA, s.name), { ...runOpts(flags, s.year), title: s.title });
      const rec = r.rec;
      const t = (ms?: number) => (ms === undefined ? '-' : formatWall(ms));
      const showCase = (id: string) => {
        const c = rec.cases.find((x) => x.id === id);
        if (!c) return console.log(`no case ${id}`);
        console.log(`\n${c.id}: ${c.priority}, ${c.withdrawn ? 'withdrawn' : c.decision ?? 'pending'}; clock starts ${t(c.receivedAt)}, decided ${t(c.decidedAt)}${c.decidedAt ? ` (${((c.decidedAt - c.receivedAt) / 3.6e6).toFixed(1)} h)` : ''}`);
        console.log(`  member ${c.memberId} service ${c.cpt}; decision taken from ${c.decisionSource ?? '-'}`);
        for (const ref of c.records) {
          const x = rec.byRef.get(ref)!;
          console.log(`  - ${ref.padEnd(22)} ${x.kind.padEnd(10)} recv ${t(x.receivedAt)}  ${x.decision ?? (x.closedDuplicate ? 'closed-dup' : x.withdrawn ? 'withdrawn' : '')} ${x.decidedAt ? t(x.decidedAt) : ''} ${x.authNumber ?? ''}`);
          for (const i of x.issues) console.log(`      ! ${i}`);
        }
        for (const a of c.appeals) console.log(`  - ${a} (appeal)`);
        for (const k of c.conflicts) console.log(`  CONFLICT ${k}`);
      };
      if (flags.case) showCase(flags.case);
      else if (flags.record) {
        const id = rec.caseOfRecord.get(flags.record);
        id ? showCase(id) : console.log(`record ${flags.record} is not part of any case (inquiry or orphan?)`);
      } else if (flags.metric) {
        const m = r.reconciled.metrics.find((x) => x.key === flags.metric);
        if (!m) return console.log(`unknown metric. Known: ${r.reconciled.metrics.map((x) => x.key).join(', ')}`);
        console.log(`${m.label}: ${m.value}${m.unit === '%' ? '%' : m.unit === 'hours' ? ' h' : ''}${m.denominator !== undefined ? ` (${m.numerator}/${m.denominator})` : ''}`);
        console.log(`definition: ${m.definition}`);
        console.log(`first 10 of ${m.ids.length}: ${m.ids.slice(0, 10).join(', ')}`);
        if (m.ids[0]) showCase(rec.caseOfAppeal.get(m.ids[0]) ?? m.ids[0]);
      } else console.log('use --case C00012, --record fax:FX-000031 or --metric standard.approvedPct');
      break;
    }
    default:
      console.log(readFileSync(new URL(import.meta.url)).toString().split('\n').slice(1, 7).join('\n').replace(/^\/\/ ?/gm, ''));
  }
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
